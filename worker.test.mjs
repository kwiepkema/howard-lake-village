import assert from 'node:assert/strict';
import worker from './worker.mjs';
const env={RESEND_API_KEY:'mock',CONTACT_FROM:'onboarding@resend.dev',CONTACT_TO:'owner@example.com',TURNSTILE_SECRET_KEY:'mock',CONTACT_RATE_LIMITER:{limit:async()=>({success:true})}};
const fields={'contact-name':'Test','contact-email':'guest@example.com','contact-subject':'Question','contact-message':'Hello'};
const request=(data,origin='https://test.example')=>new Request('https://test.example/api/contact',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify(data)});
const payload={kind:'contact',fields,token:'token'};
let calls=[];
globalThis.fetch=async(url,options)=>{
 calls.push({url,options});
 return Response.json(url.includes('siteverify')?{success:true,hostname:'test.example',action:'contact'}:{id:'mock-id'});
};
assert.equal((await worker.fetch(request(payload),{})).status,503);
assert.equal((await worker.fetch(request(payload,'https://evil.example'),env)).status,403);
assert.equal((await worker.fetch(request({...payload,fields:{...fields,'contact-email':'bad'}}),env)).status,400);
assert.equal(calls.length,0);
assert.equal((await worker.fetch(request(payload),env)).status,200);
const sent=JSON.parse(calls[1].options.body);
assert.equal(sent.reply_to,'guest@example.com');
assert.equal(sent.to[0],env.CONTACT_TO);
calls=[];
globalThis.fetch=async()=>Response.json({success:false});
assert.equal((await worker.fetch(request(payload),env)).status,400);
assert.equal((await worker.fetch(request(payload),{...env,CONTACT_RATE_LIMITER:{limit:async()=>({success:false})}})).status,429);
globalThis.fetch=async url=>url.includes('siteverify')?Response.json({success:true,hostname:'test.example',action:'contact'}):new Response('',{status:500});
assert.equal((await worker.fetch(request(payload),env)).status,502);
const stay={kind:'availability',token:'token',fields:{accommodation:'The Villa','arrival-date':'2027-02-01','departure-date':'2027-02-03','guest-count':'2','first-name':'Test','last-name':'Guest',email:'guest@example.com'}};
assert.equal((await worker.fetch(request({...stay,fields:{...stay.fields,'departure-date':'2027-01-01'}}),env)).status,400);
globalThis.fetch=async url=>Response.json(url.includes('siteverify')?{success:true,hostname:'test.example',action:'contact'}:{id:'mock-id'});
assert.equal((await worker.fetch(request(stay),env)).status,200);
console.log('Worker checks passed: configuration, origin, validation, Reply-To, delivery failure, spam and rate limit. No email sent.');
